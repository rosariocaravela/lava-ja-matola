const SERVICE_POINTS_BY_CATEGORY = {
  BÁSICA: 10,
  COMPLETA: 20,
  MECÂNICA: 25,
  PREMIUM: 30,
  ESPECIALIZADA: 40
};
const REWARD_POINT_COSTS = {
  AIR_FRESHENER: 50,
  WAX_APPLICATION: 100,
  WASH_DISCOUNT: 150,
  FREE_EXTERIOR_WASH: 200
};
const WELCOME_BONUS_POINTS = 10;
const RECURRING_BONUS_POINTS = 10;
const RECURRING_BONUS_WEEKS = 3;
const RECURRING_BONUS_DAYS = RECURRING_BONUS_WEEKS * 7;
const MINIMUM_REWARD_POINTS = Math.min(...Object.values(REWARD_POINT_COSTS));

function getPointsForCategory(category) {
  const normalizedCategory = String(category || '').trim().toLocaleUpperCase('pt');
  return SERVICE_POINTS_BY_CATEGORY[normalizedCategory] || SERVICE_POINTS_BY_CATEGORY.BÁSICA;
}

module.exports = {
  SERVICE_POINTS_BY_CATEGORY,
  getPointsForCategory,
  REWARD_POINT_COSTS,
  WELCOME_BONUS_POINTS,
  RECURRING_BONUS_POINTS,
  RECURRING_BONUS_WEEKS,
  RECURRING_BONUS_DAYS,
  MINIMUM_REWARD_POINTS
};
